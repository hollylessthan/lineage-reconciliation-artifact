"""Generate the manuscript's path-by-relation matrix from frozen protocol-v1 job logs.

Usage: python scripts/make_paper_matrix.py RUN_ID --output paper/tables/path-matrix.tex
       [--logs DIR]   (DIR holds jobs.tsv and <job_id>.log; otherwise logs are fetched)
Cell codes: H holds in 3/3, V replicated violation, C characterization difference,
D documented deviation, - not applicable / not run, X path inadmissible.
Analysis only; it applies the frozen rules in analyze_protocol.py.
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

import analyze_protocol as ap

RELS = ['MR1a', 'MR1b', 'MR1c', 'MR2a', 'MR2b', 'MR3', 'MR4a', 'MR4b', 'MR5', 'MR5i', 'MR7', 'MR9a', 'MR9b', 'MR9c']
DEVIATIONS = {('om-ol', 'MR9a'), ('om-ol', 'MR9c')}
# Contract per path, as assigned in the adapters (metamorphic_native.py, engines.py, round2b.py)
# from docs/contract-and-predictions.md; the job logs do not record it.
CONTRACT = {'dh-ol-patch': 'A', 'dh-view-incremental': 'A', 'om-dbt-default': 'A', 'om-ol': 'U'}
ENGINE = {'': 'PostgreSQL', 'mysql': 'MySQL', 'mariadb': 'MariaDB', 'clickhouse': 'ClickHouse', 'trino': 'Trino', 'mssql': 'SQL Server'}


def pretty(label):
    base, _, ver = label.partition(' [')
    ver = ver.rstrip(']').replace('DataHub ', '').replace('OpenMetadata ', '').lstrip('v')
    prod, rest = base.split('-', 1) if '-' in base else (base, '')
    if prod in ('dh', 'om'):
        ver = ver or ('1.8.0' if prod == 'dh' else '2.0.7')
    product = {'dh': 'DataHub', 'om': 'OpenMetadata', 'marquez': 'Marquez 0.51.1', 'odd': 'ODD 0.29.0'}[prod]
    if rest.startswith('view'):
        eng = rest[5:] if rest.startswith('view-') and rest[5:] in ENGINE else ''
        mode = ' incremental' if rest == 'view-incremental' else (' override' if prod == 'om' else '')
        what = f'view{mode}, {ENGINE[eng]}'
    else:
        what = {'dbt': 'dbt', 'dbt-override': 'dbt override', 'dbt-default': 'dbt default', 'ol': 'OpenLineage UPSERT' if prod == 'dh' else 'OpenLineage',
                'ol-patch': 'OpenLineage PATCH'}[rest]
    return f"{product}{' ' + ver if ver else ''} {what}"


def logs(run_id, cache):
    if cache:
        for line in (cache / 'jobs.tsv').read_text().splitlines():
            jid, name = line.split('\t', 1)
            yield name, (cache / f'{jid}.log').read_text()
        return
    for j in ap.jobs(run_id):
        if j['conclusion'] != 'skipped':
            yield j['name'], ap.gh(f"repos/{ap.REPO}/actions/jobs/{j['id']}/logs")


def main():
    p = argparse.ArgumentParser()
    p.add_argument('run_id')
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--logs', type=Path)
    a = p.parse_args()
    table = defaultdict(dict)
    for name, log in logs(a.run_id, a.logs):
        m = ap.REP.search(name)
        if not m:
            continue
        for path, rec in ap.parse(log).items():
            if path == 'dh-real':
                continue
            rec['admissible'], _ = ap.admissible(rec)
            table[ap.label(name, path)][int(m.group(1))] = rec
    rows = []
    for label in sorted(table):
        reps = table[label]
        base = label.split(' ')[0]
        adm = [r for r in reps.values() if r['admissible']]
        cells = []
        for rel in RELS:
            if len(adm) < 3:
                cells.append('X')
                continue
            vals = {r['rels'].get(rel) for r in adm}
            v = vals.pop() if len(vals) == 1 else 'unstable'
            cells.append({'holds': 'H', 'violation': 'V', 'differs': 'C', None: '-', 'not_applicable': '-'}.get(v, '?'))
            if (base, rel) in DEVIATIONS and cells[-1] in ('V', 'C'):
                cells[-1] = 'D'
        rows.append((pretty(label), CONTRACT.get(base, 'R'), cells))
    rows.sort()
    head = ' & '.join(['Path', 'K'] + [r.replace('MR', '') for r in RELS])
    lines = ['% Generated by scripts/make_paper_matrix.py from protocol-v1 run ' + a.run_id + '. Do not edit by hand.',
             r'\begin{table*}[t]',
             r'\caption{Replicated outcome of every relation on every configured path (frozen run, three repetitions). '
             r'K: contract (R Replace, A Additive, U Undetermined). H holds; V replicated violation; C characterization '
             r'difference; D documented deviation; -- not applicable to the path. Inadmissible paths are marked X and receive no verdicts.}',
             r'\label{tab:matrix}', r'\centering', r'\scriptsize', r'\setlength{\tabcolsep}{2.6pt}',
             r'\begin{tabular}{@{}ll' + 'c' * len(RELS) + '@{}}', r'\toprule', head + r' \\', r'\midrule']
    group_prev = None
    for label, k, cells in rows:
        if label.startswith('DataHub '):
            group = 'DataHub: ' + ('OpenLineage' if 'OpenLineage' in label else ('dbt' if 'dbt' in label else 'SQL views'))
        elif label.startswith('OpenMetadata '):
            group = 'OpenMetadata: ' + ('OpenLineage' if 'OpenLineage' in label else ('dbt' if 'dbt' in label else 'SQL views'))
        else:
            group = 'Other catalogs'
        if group != group_prev:
            lines.append('\\addlinespace[3pt]')
            lines.append('\\multicolumn{16}{@{}l}{\\textit{' + group + '}} \\\\')
            group_prev = group
        tex_label = label
        if cells[0] == 'X':
            lines.append(f"{tex_label} & {k} & " + r'\multicolumn{' + str(len(RELS)) + r'}{l}{X (inadmissible in 3/3)} \\')
            continue
        lines.append(f"{tex_label} & {k} & " + ' & '.join(c if c != '-' else '--' for c in cells) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table*}']
    a.output.write_text('\n'.join(lines) + '\n')
    print(json.dumps({'paths': len(rows), 'violations': sum(c.count('V') for _, _, c in rows)}))


if __name__ == '__main__':
    main()
